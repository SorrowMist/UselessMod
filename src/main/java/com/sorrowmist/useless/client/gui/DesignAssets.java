package com.sorrowmist.useless.client.gui;

import com.google.gson.Gson;
import com.google.gson.reflect.TypeToken;
import com.mojang.blaze3d.systems.RenderSystem;
import com.mojang.blaze3d.vertex.BufferBuilder;
import com.mojang.blaze3d.vertex.BufferUploader;
import com.mojang.blaze3d.vertex.DefaultVertexFormat;
import com.mojang.blaze3d.vertex.Tesselator;
import com.mojang.blaze3d.vertex.VertexFormat;
import com.sorrowmist.useless.UselessMod;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.renderer.GameRenderer;
import net.minecraft.resources.ResourceLocation;
import org.joml.Matrix4f;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.Set;

/**
 * Original Liquid Glass artwork, not screenshots or approximated rectangles.
 * Geometry is generated by tools/apple_ui/import_design_assets.py. The target
 * rectangle always denotes the component BODY; baked shadows/focus rings extend
 * outside it, never shrink its hitbox or stretch its rounded corners.
 */
public final class DesignAssets {
    private DesignAssets() {}
    private static final class Catalog {
        static final Map<String, Slice> SLICES = load();
        private static Map<String, Slice> load() {
            try (var stream = Objects.requireNonNull(DesignAssets.class.getResourceAsStream(
                    "/assets/useless_mod/design/slice_geometry.json"), "Missing design slice geometry");
                 var reader = new InputStreamReader(stream, StandardCharsets.UTF_8)) {
                Map<String, Slice> result = new Gson().fromJson(reader, new TypeToken<Map<String, Slice>>() {}.getType());
                return Map.copyOf(result);
            } catch (java.io.IOException exception) {
                throw new IllegalStateException("Cannot load original design slices", exception);
            }
        }
    }

    public record Slice(String path, int[] size, int[] body, float corner, boolean fixedCorners) {
        /** Destination positions including baked outer effects (six boundaries). */
        public float[] axis(float origin, float length, boolean horizontal) {
            int a = horizontal ? 0 : 1, dimension = horizontal ? 2 : 3;
            float scale = fixedCorners ? .5f : length / body[dimension];
            float c = Math.min(length / 2, corner * scale);
            return new float[]{origin - body[a] * scale, origin, origin + c,
                    origin + length - c, origin + length,
                    origin + length + (size[a] - body[a] - body[dimension]) * scale};
        }
        public float[] uv(boolean horizontal) {
            int a = horizontal ? 0 : 1, dimension = horizontal ? 2 : 3;
            float c = Math.min(corner, body[dimension] / 2f);
            return new float[]{0, body[a], body[a] + c, body[a] + body[dimension] - c,
                    body[a] + body[dimension], size[a]};
        }
    }

    public static Set<String> keys() { return Catalog.SLICES.keySet(); }
    public static Slice slice(String key) {
        Slice slice = Catalog.SLICES.get(key.toLowerCase(Locale.ROOT));
        if (slice == null) throw new IllegalArgumentException("Unknown design slice: " + key);
        return slice;
    }

    public static ResourceLocation resource(String key, int density) {
        Slice slice = slice(key);
        if (slice.path().startsWith("reference/"))
            return new ResourceLocation(UselessMod.MODID, "textures/gui/design/" + slice.path() + ".png");
        int factor = density >= 4 ? 4 : 2;
        return new ResourceLocation(UselessMod.MODID, "textures/gui/design/" + slice.path() + "_" + factor + "x.png");
    }

    public static void draw(GuiGraphics g, String key, float x, float y, float w, float h) {
        drawTinted(g, key, x, y, w, h, 0xFFFFFFFF);
    }

    public static void drawTinted(GuiGraphics g, String key, float x, float y, float w, float h, int argb) {
        if (w <= 0 || h <= 0 || (argb >>> 24) == 0) return;
        Slice slice = slice(key);
        float[] xs = slice.axis(x, w, true), ys = slice.axis(y, h, false);
        // Controls retain isotropic corner/shadow sizes even when widened.
        if (!slice.fixedCorners()) {
            float scale = h / slice.body()[3];
            float corner = Math.min(w / 2, slice.corner() * scale);
            xs = new float[]{x - slice.body()[0] * scale, x, x + corner, x + w - corner, x + w,
                    x + w + (slice.size()[0] - slice.body()[0] - slice.body()[2]) * scale};
        }
        float[] us = slice.uv(true), vs = slice.uv(false);
        double guiScale = Minecraft.getInstance().getWindow().getGuiScale();
        int density = guiScale >= 3 ? 4 : 2;
        g.flush();
        RenderSystem.setShaderTexture(0, resource(key, density));
        RenderSystem.setShader(GameRenderer::getPositionTexColorShader);
        RenderSystem.enableBlend();
        RenderSystem.defaultBlendFunc();
        Matrix4f matrix = g.pose().last().pose();
        BufferBuilder buffer = Tesselator.getInstance().getBuilder();
        buffer.begin(VertexFormat.Mode.QUADS, DefaultVertexFormat.POSITION_TEX_COLOR);
        for (int row = 0; row < 5; row++) for (int col = 0; col < 5; col++) {
            if (xs[col+1] <= xs[col] || ys[row+1] <= ys[row] || us[col+1] <= us[col] || vs[row+1] <= vs[row]) continue;
            vertex(buffer, matrix, xs[col], ys[row], us[col]/slice.size()[0], vs[row]/slice.size()[1], argb);
            vertex(buffer, matrix, xs[col], ys[row+1], us[col]/slice.size()[0], vs[row+1]/slice.size()[1], argb);
            vertex(buffer, matrix, xs[col+1], ys[row+1], us[col+1]/slice.size()[0], vs[row+1]/slice.size()[1], argb);
            vertex(buffer, matrix, xs[col+1], ys[row], us[col+1]/slice.size()[0], vs[row]/slice.size()[1], argb);
        }
        BufferUploader.drawWithShader(buffer.end());
    }

    private static void vertex(BufferBuilder b, Matrix4f m, float x, float y, float u, float v, int color) {
        b.vertex(m, x, y, 0).uv(u, v).color((color >>> 16) & 255, (color >>> 8) & 255,
                color & 255, color >>> 24).endVertex();
    }

    public static void button(GuiGraphics g, int x, int y, int w, int h, String kind,
                              boolean hovered, boolean pressed, boolean active) {
        String state = !active ? "disabled" : pressed ? "pressed" : hovered ? "hover" : "default";
        String prefix = h <= 14 ? "button_capsule_" + kind + "_sm_" : "button_" + kind + "_";
        draw(g, prefix + state, x, y, w, h);
    }

    /** Closest semantic token, rather than exact ARGB equality or RGB ordering. */
    public static String colorName(int argb) {
        int[] colors = {0x007AFF,0x34C759,0xFF9F0A,0xFF3B30,0xAF52DE,0x30B0C7,0x8E8E93,0x5856D6};
        String[] names = {"blue","green","orange","red","purple","teal","gray","indigo"};
        long best = Long.MAX_VALUE; int winner = 0;
        for (int i = 0; i < colors.length; i++) {
            long r = ((argb >>> 16)&255) - ((colors[i] >>> 16)&255);
            long green = ((argb >>> 8)&255) - ((colors[i] >>> 8)&255);
            long b = (argb&255) - (colors[i]&255);
            long distance = r*r + green*green + b*b;
            if (distance < best) { best = distance; winner = i; }
        }
        return names[winner];
    }
}
